from timeit import timeit
from constants import NUMBERS, SEARCH_FIRST, SEARCH_MIDDLE, SEARCH_LAST, SEARCH_MISSING


def find_index(arr, target):
    for i in range(len(arr)):
        if arr[i] == target:
            return i
    return -1


# --- Задание 2. Сложность алгоритма ---
#
# Время: O(n). Чем больше список, тем дольше ищем.
# В лучшем случае элемент первый - тогда O(1).
# В худшем - элемента нет или он в конце, тогда проходим весь список.
#
# Память: O(1). Новые списки не создаем, только переменная i в цикле.


print("Задание 3. Список из 100 случайных чисел")

for value in [SEARCH_FIRST, SEARCH_MIDDLE, SEARCH_LAST, SEARCH_MISSING]:
    result = find_index(NUMBERS, value)
    elapsed = timeit(lambda v=value: find_index(NUMBERS, v), number=1000)
    print(f"Ищем {value}, индекс: {result}, время: {elapsed:.6f} сек (1000 запусков)")


print("\nЗадание 4. Сравнение времени для разных размеров")

for size in [10, 100, 1000]:
    arr = list(range(size))
    elapsed = timeit(lambda: find_index(arr, size - 1), number=1000)
    print(f"Размер {size}: {elapsed:.6f} сек (1000 запусков)")

print("\nВывод: когда размер списка растет в 10 раз, время тоже примерно растет в 10 раз.")
print("Значит алгоритм линейный - O(n).")

